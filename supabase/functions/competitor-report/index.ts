serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const { email, business_name, city, industry, order_id } = await req.json();

    if (!email || !city || !industry) {
      return new Response(
        JSON.stringify({ error: "email, city, and industry are required" }),
        { status: 400, headers: { ...corsHeaders, "Content-Type": "application/json" } },
      );
    }

    const sb = createClient(SUPABASE_URL, SUPABASE_SERVICE_KEY);

    // Idempotency check
    if (order_id) {
      const { data: existing } = await sb
        .from("competitor_reports")
        .select("status,report_text")
        .eq("id", order_id)
        .maybeSingle();
      if (existing?.status === "delivered") {
        console.log(`[competitor-report] Already delivered for order ${order_id}`);
        return new Response(JSON.stringify({ ok: true, cached: true }), {
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
    }

    // Mark processing
    if (order_id) {
      await sb.from("competitor_reports").update({ status: "processing" }).eq("id", order_id);
    }

    // Pull real competitor data from Google Maps
    const competitors = await findCompetitors(business_name || "", city, industry);
    console.log(
      `[competitor-report] Found ${competitors.length} competitors for ${industry} in ${city}`,
    );

    // Generate report via Claude
    const reportText = await generateReport(
      business_name || "",
      city,
      industry,
      competitors,
    );

    // Send email
    await sendReportEmail(email, business_name || city, reportText);

    // Update order record
    const updatePayload = {
      status: "delivered",
      report_text: reportText,
      competitors_json: JSON.stringify(competitors),
    };
    if (order_id) {
      await sb.from("competitor_reports").update(updatePayload).eq("id", order_id);
    } else {
      await sb.from("competitor_reports").insert({
        email,
        business_name: business_name || null,
        city,
        industry,
        ...updatePayload,
      });
    }

    console.log(`[competitor-report] Report delivered to ${email} for ${industry} in ${city}`);

    return new Response(JSON.stringify({ ok: true }), {
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  } catch (err: any) {
    console.error("[competitor-report]", err);
    try {
      await fetch(`${SUPABASE_URL}/rest/v1/delivery_failures`, {
        method: "POST",
        headers: { "Content-Type": "application/json", "apikey": SUPABASE_SERVICE_KEY, "Authorization": `Bearer ${SUPABASE_SERVICE_KEY}`, "Prefer": "return=minimal" },
        body: JSON.stringify({ function_name: "competitor-report", error_message: err.message || String(err) }),
      });
    } catch (_) {}
    try {
      await fetch("https://api.resend.com/emails", {
        method: "POST",
        headers: { "Authorization": `Bearer ${RESEND_API_KEY}`, "Content-Type": "application/json" },
        body: JSON.stringify({
          from: "Matt Michels <matt@mattmichelstraining.com>",
          to: "matt@mattmichelstraining.com",
          subject: "⚠️ Delivery Failed: competitor-report",
          html: `<p><strong>Function:</strong> competitor-report</p><p><strong>Error:</strong> ${err.message || String(err)}</p><p><strong>Time:</strong> ${new Date().toISOString()}</p>`,
        }),
      });
    } catch (_) {}
    return new Response(JSON.stringify({ error: err.message }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
