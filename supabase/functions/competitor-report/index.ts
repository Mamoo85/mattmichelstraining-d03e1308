async function generateReport(businessName: string, city: string, industry: string, competitors: CompetitorData[]): Promise<string> {
  const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
    method: "POST",
    headers: {
      "Authorization": `Bearer ${LOVABLE_API_KEY}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      model: "google/gemini-2.5-flash",
      messages: [{ role: "user", content: buildPrompt(businessName, city, industry, competitors) }],
      max_tokens: 2500,
    }),
  });

  if (!response.ok) {
    const err = await response.text();
    throw new Error(`AI Gateway error: ${err}`);
  }

  const data = await response.json();
  return data.choices?.[0]?.message?.content || "";
}

