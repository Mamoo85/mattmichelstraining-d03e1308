serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const { email, business_name, city, industry, order_id } = await req.json();

    if (!email || !city || !industry) {
      return new Response(
        JSON.stringify({ error: "email, city, and industry are required" }),
        { status: 400, headers: { ...corsHeaders, "Content-Type": "application/json" } },
      );
    }

    const sb = createClient(SUPABASE_URL, SUPABASE_SERVICE_KEY);

    if (order_id) {
      const { data: existing } = await sb.from("competitor_reports").select("status,report_text").eq("id", order_id).maybeSingle();
      if (existing?.status === "delivered") {
        console.log(`[competitor-report] Already delivered for order ${order_id}`);
        return new Response(JSON.stringify({ ok: true, cached: true }), {
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
    }

    if (order_id) {
      await sb.from("competitor_reports").update({ status: "processing" }).eq("id", order_id);
    }

    const competitors = await findCompetitors(business_name || "", city, industry);
    console.log(`[competitor-report] Found ${competitors.length} competitors for ${industry} in ${city}`);

    const reportText = await generateReport(business_name || "", city, industry, competitors);
    await sendReportEmail(email, business_name || city, reportText);

    const updatePayload = { status: "delivered", report_text: reportText, competitors_json: JSON.stringify(competitors) };
    if (order_id) {
      await sb.from("competitor_reports").update(updatePayload).eq("id", order_id);
    } else {
      await sb.from("competitor_reports").insert({ email, business_name: business_name || null, city, industry, ...updatePayload });
    }

    console.log(`[competitor-report] Report delivered to ${email} for ${industry} in ${city}`);

    return new Response(JSON.stringify({ ok: true }), {
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  } catch (err: any) {
    console.error("[competitor-report]", err);
    try {
      const sb = createClient(SUPABASE_URL, SUPABASE_SERVICE_KEY);
      const body = await req.clone().json().catch(() => ({}));
      await sb.from("delivery_failures").insert({
        function_name: "competitor-report",
        error_message: err.message,
        customer_email: body.email || null,
        order_id: body.order_id || null,
      });
      if (RESEND_API_KEY) {
        await fetch("https://api.resend.com/emails", {
          method: "POST",
          headers: { Authorization: `Bearer ${RESEND_API_KEY}`, "Content-Type": "application/json" },
          body: JSON.stringify({
            from: "M² Alerts <matt@mattmichelstraining.com>",
            to: ["matt@mattmichelstraining.com"],
            subject: `🚨 DELIVERY FAILED — competitor-report — ${body.email || "unknown"}`,
            html: `<p><strong>Function:</strong> competitor-report</p><p><strong>Customer:</strong> ${body.email || "unknown"}</p><p><strong>Error:</strong> ${err.message}</p>`,
          }),
        });
      }
    } catch (alertErr) { console.error("[competitor-report] Alert failed:", alertErr); }
    return new Response(JSON.stringify({ error: err.message }), {
      status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
