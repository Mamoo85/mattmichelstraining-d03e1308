import { serve } from "https://deno.land/std@0.190.0/http/server.ts";
import { createClient } from "https://esm.sh/@supabase/supabase-js@2";

const SUPABASE_URL = Deno.env.get("SUPABASE_URL") || "";
const SUPABASE_SERVICE_KEY = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY") || "";
const ANTHROPIC_API_KEY = Deno.env.get("ANTHROPIC_API_KEY") || "";
const GOOGLE_MAPS_API_KEY = Deno.env.get("GOOGLE_MAPS_API_KEY") || "";
const RESEND_API_KEY = Deno.env.get("RESEND_API_KEY") || "";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

interface CompetitorData {
  name: string;
  rating: number;
  totalReviews: number;
  address: string;
  types: string[];
  priceLevel?: number;
}

async function findCompetitors(
  businessName: string,
  city: string,
  industry: string,
): Promise<CompetitorData[]> {
  const query = `${industry} near ${city}`;
  const url = `https://maps.googleapis.com/maps/api/place/textsearch/json?query=${encodeURIComponent(query)}&key=${GOOGLE_MAPS_API_KEY}`;
  const res = await fetch(url);
  if (!res.ok) return [];
  const data = await res.json();
  const results = (data.results || []).slice(0, 15);

  return results
    .filter((r: any) => r.name?.toLowerCase() !== businessName?.toLowerCase())
    .map((r: any) => ({
      name: r.name || "Unknown",
      rating: r.rating || 0,
      totalReviews: r.user_ratings_total || 0,
      address: r.formatted_address || "",
      types: r.types || [],
      priceLevel: r.price_level,
    }));
}

